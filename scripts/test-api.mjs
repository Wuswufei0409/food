import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
const base=process.env.TEST_BASE_URL || "http://127.0.0.1:5173";
if(!["127.0.0.1","localhost"].includes(new URL(base).hostname))throw new Error("Tests write disposable records: local server only.");
let checks=0;
const session=await fetch(base+"/api/session");assert.equal(session.status,200);checks++;
const cookie=session.headers.get("set-cookie").split(";")[0];const {csrf}=await session.json();
const headers={"Content-Type":"application/json",Origin:base,Cookie:cookie,"X-CSRF-Token":csrf};
const post=(body,overrides={})=>fetch(base+"/api/answers",{method:"POST",headers:{...headers,...overrides},body:typeof body==="string"?body:JSON.stringify(body)});
const choice={id:randomUUID(),kind:"restaurants",selected:["mujinyu","tegu"],message:""};
assert.equal((await post(choice)).status,201);checks++;
assert.equal((await post(choice)).status,200);checks++;
assert.equal((await post({...choice,message:"changed",kind:"idea",selected:[]})).status,409);checks++;
assert.equal((await post({...choice,id:randomUUID(),selected:[]})).status,400);checks++;
assert.equal((await post({...choice,id:randomUUID(),selected:["unknown"]})).status,400);checks++;
assert.equal((await post({...choice,id:randomUUID(),selected:["tegu","tegu"]})).status,400);checks++;
assert.equal((await post(choice,{Origin:"https://other.example"})).status,403);checks++;
assert.equal((await post(choice,{"X-CSRF-Token":"invalid"})).status,403);checks++;
assert.equal((await post("{" )).status,400);checks++;
const idea={id:randomUUID(),kind:"idea",selected:[],message:"本地测试：想吃火锅！\n<script>alert('test')</script>"};
assert.equal((await post(idea)).status,201);checks++;
assert.equal((await post({...idea,id:randomUUID(),message:"   "})).status,400);checks++;
assert.equal((await post({...idea,id:randomUUID(),message:"字".repeat(1001)})).status,400);checks++;
assert.equal((await post("x".repeat(10001))).status,413);checks++;
assert.equal((await fetch(base+"/api/export")).status,403);checks++;
const concurrent={...choice,id:randomUUID()};
const responses=await Promise.all([post(concurrent),post(concurrent)]);
assert.deepEqual(responses.map(r=>r.status).sort(),[200,201]);checks++;
for(let i=0;i<7;i++)assert.equal((await post({...choice,id:randomUUID()})).status,201);
assert.equal((await post({...choice,id:randomUUID()})).status,429);checks++;
console.log(`${checks} API checks passed: persistence, idempotency, concurrency, validation, CSRF, size limit, rate limit, private export.`);
